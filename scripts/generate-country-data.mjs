import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

import { countries, languages } from "countries-list"
import { currencies } from "countries-list/currencies"
import isoCountries from "i18n-iso-countries"
import { getCountries, getCountryCallingCode } from "libphonenumber-js/max"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const PACKAGE_FILE = join(ROOT, "package.json")
const FLAGS_FILE = join(ROOT, "src/components/flags/flag-data.ts")
const OUTPUT_DIR = join(ROOT, "src/components/flags/data")
const SITE_META_FILE = join(ROOT, "src/config/country-data-meta.ts")
const HEADER = `// SPDX-License-Identifier: MIT

// Generated by scripts/generate-country-data.mjs from countries-list,
// i18n-iso-countries, and libphonenumber-js. Do not edit by hand.

`

function flagCodes() {
  const source = readFileSync(FLAGS_FILE, "utf8")
  const start = source.indexOf("export const flagNames = {")
  const end = source.indexOf("\n} as const", start)
  if (start < 0 || end < 0) throw new Error("Could not find flagNames in flag-data.ts")

  return new Set(source.slice(start, end).split("\n").flatMap((line) => {
    const match = line.match(/^\s+(?:"([^"]+)"|([a-z]{2})): /)
    return match ? [match[1] || match[2]] : []
  }))
}

function serialize(value) {
  return JSON.stringify(value, null, 2)
}

function makeCountryData() {
  const supportedCallingCodes = new Set(getCountries())
  const availableFlags = flagCodes()

  return Object.entries(countries)
    .filter(([alpha2]) => availableFlags.has(alpha2.toLowerCase()))
    .map(([alpha2, country]) => {
      const code = alpha2.toLowerCase()
      const numeric = isoCountries.alpha2ToNumeric(alpha2)
      const callingCodes = supportedCallingCodes.has(alpha2)
        ? [`+${getCountryCallingCode(alpha2)}`]
        : country.phone.map((callingCode) => `+${callingCode}`)

      return {
        code,
        alpha2,
        alpha3: isoCountries.alpha2ToAlpha3(alpha2) || "",
        numeric: numeric ? String(numeric).padStart(3, "0") : "",
        name: country.name,
        nativeName: country.native,
        aliases: country.alias || [],
        emoji: alpha2.replace(/[A-Z]/g, (letter) => String.fromCodePoint(letter.charCodeAt(0) + 127397)),
        callingCodes: [...new Set(callingCodes)],
        continent: country.continent,
        capital: country.capital,
        currencies: country.currency,
        languages: country.languages,
      }
    })
    .sort((a, b) => a.name.localeCompare(b.name))
}

function assertUnique(items, key, label, { allowEmpty = false } = {}) {
  const values = new Set()
  for (const item of items) {
    const value = item[key]
    if (!value && allowEmpty) continue
    if (!value) throw new Error(`${label} is missing for ${item.code}`)
    if (values.has(value)) throw new Error(`Duplicate ${label}: ${value}`)
    values.add(value)
  }
}

function validateData(countryData, languageData, currencyData, phoneCountryCodes) {
  const languageCodes = new Set(languageData.map((language) => language.code))
  const currencyCodes = new Set(currencyData.map((currency) => currency.code))
  const phoneCodes = new Set(phoneCountryCodes)

  assertUnique(countryData, "code", "country code")
  assertUnique(countryData, "alpha2", "ISO alpha-2")
  assertUnique(countryData, "alpha3", "ISO alpha-3")
  assertUnique(countryData, "numeric", "ISO numeric", { allowEmpty: true })
  assertUnique(languageData, "code", "language code")
  assertUnique(currencyData, "code", "currency code")

  for (const country of countryData) {
    const emojiCode = [...country.emoji]
      .map((character) => String.fromCharCode(character.codePointAt(0) - 127397))
      .join("")
    if (emojiCode !== country.alpha2) throw new Error(`Emoji does not round-trip for ${country.code}`)
    for (const language of country.languages) {
      if (!languageCodes.has(language)) throw new Error(`Unknown language ${language} on ${country.code}`)
    }
    for (const currency of country.currencies) {
      if (!currencyCodes.has(currency)) throw new Error(`Unknown currency ${currency} on ${country.code}`)
    }
    if (phoneCodes.has(country.code)) {
      const authoritativeCallingCode = `+${getCountryCallingCode(country.alpha2)}`
      if (country.callingCodes[0] !== authoritativeCallingCode) {
        throw new Error(`Calling code mismatch for ${country.code}: expected ${authoritativeCallingCode}`)
      }
    }
  }
}

function makeLanguageData() {
  return Object.entries(languages)
    .map(([code, language]) => ({
      code,
      name: language.name,
      nativeName: language.native,
      direction: language.rtl ? "rtl" : "ltr",
    }))
    .sort((a, b) => a.name.localeCompare(b.name))
}

function makeCurrencyData() {
  return Object.entries(currencies)
    .map(([code, currency]) => ({ code, ...currency }))
    .sort((a, b) => a.code.localeCompare(b.code))
}

mkdirSync(OUTPUT_DIR, { recursive: true })

const countryData = makeCountryData()
const languageData = makeLanguageData()
const currencyData = makeCurrencyData()
const supportedPhoneAlpha2 = new Set(getCountries())
const phoneCountryCodes = countryData
  .filter((country) => supportedPhoneAlpha2.has(country.alpha2))
  .map((country) => country.code)
const packageJson = JSON.parse(readFileSync(PACKAGE_FILE, "utf8"))

validateData(countryData, languageData, currencyData, phoneCountryCodes)

const countryDataMeta = {
  generated: true,
  validated: true,
  countryCount: countryData.length,
  phoneCountryCount: phoneCountryCodes.length,
  sources: {
    countries: `countries-list@${packageJson.devDependencies["countries-list"].replace("^", "")}`,
    iso: `i18n-iso-countries@${packageJson.devDependencies["i18n-iso-countries"].replace("^", "")}`,
    phone: `libphonenumber-js@${packageJson.dependencies["libphonenumber-js"].replace("^", "")}`,
  },
}

writeFileSync(SITE_META_FILE, `${HEADER}export const countryDataMeta = ${serialize(countryDataMeta)} as const
`)

writeFileSync(join(OUTPUT_DIR, "countries.ts"), `${HEADER}export const countryDataMeta = ${serialize(countryDataMeta)} as const

export const countryData = ${serialize(countryData)} as const

export const phoneCountryCodes = ${serialize(phoneCountryCodes)} as const

export type Country = (typeof countryData)[number]
export type CountryCode = Country["code"]
export type PhoneCountryCode = (typeof phoneCountryCodes)[number]
export type CountryAlpha2 = Country["alpha2"]
export type CountryAlpha3 = Country["alpha3"]
`)

writeFileSync(join(OUTPUT_DIR, "languages.ts"), `${HEADER}export const languageData = ${serialize(languageData)} as const

export type Language = (typeof languageData)[number]
export type LanguageCode = Language["code"]
`)

writeFileSync(join(OUTPUT_DIR, "currencies.ts"), `${HEADER}export const currencyData = ${serialize(currencyData)} as const

export type Currency = (typeof currencyData)[number]
export type CurrencyCode = Currency["code"]
`)

console.log(`Generated ${countryData.length} countries, ${languageData.length} languages, and ${currencyData.length} currencies.`)
